"""posixre —— 匹配耗时可预测、捕获语义为 POSIX 最左最长的正则库。

只提供库接口，没有命令行入口。

公开接口
--------
compile(pattern) -> Pattern
match(pattern, text) -> Match | None
finditer(pattern, text) -> 迭代 Match

语法子集
--------
* 字面字符（元字符需用 ``\\`` 转义）
* ``.`` 匹配任意单个字符，包括换行
* ``[abc]`` ``[a-z]`` ``[^\\d ]`` 字符类，支持区间、取反和
  ``\\d \\w \\s \\D \\W \\S`` 简写；取反简写可在类内自由组合
* 连接，``|`` 选择
* ``* + ?`` 与 ``{n} {n,} {n,m}`` 计数量词（只有贪婪语义）
* ``(...)`` 捕获分组、``(?:...)`` 不捕获分组，编号按左括号次序
* ``^`` ``$`` 分别锚定字符串开头、结尾（不是行首行尾）
* ``\\`` 转义，支持 ``\\n \\t \\r \\f \\v \\a \\0 \\xHH \\uHHHH``

不支持（编译期报错并指出字符位置）：反向引用、命名反向引用、
各类环视、单词边界 ``\\b \\B``、非贪婪/占有量词、命名分组、原子分组。

捕获语义
--------
POSIX 的最左最长：先定最左起点，再让整条匹配最长；同长时让编号小的
捕获组尽可能长。量词重复匹配一个捕获组时，该组记录最后一次参与的
位置。未参与匹配的组 span 为 None，空匹配（参与但长度为 0）为 (x, x)。

全局扫描的空匹配推进
--------------------
``finditer`` 按不重叠方式从左到右产出：下一轮从上一匹配的终点开始；
上一匹配为空时，先强制跨过终点处的一个字符再搜索，因此不会在同一
位置反复产出空串，也不会连续产出两个位置相同的空匹配。

耗时
----
底层为 Thompson NFA 集合模拟，单步存活线程数不超过 NFA 状态数，
单次匹配最坏 O(n·|Q|)，``|Q|`` 仅由模式决定，与嵌套量词无关；
引擎不存在回溯，对 ``(a|aa)*b`` 这类模式在长输入上线性给出不匹配结论。
"""

